create or replace function public.submit_homework(assignment_id bigint)
returns public.portal_assignments
language plpgsql
security definer
set search_path = ''
as $$
declare
  updated_assignment public.portal_assignments;
begin
  update public.portal_assignments
  set status = 'submitted', submitted_at = now(), updated_at = now()
  where id = assignment_id
    and student_id = (select auth.uid())
    and status = 'todo'
  returning * into updated_assignment;

  if updated_assignment.id is null then
    raise exception 'Assignment is unavailable for submission.';
  end if;
  return updated_assignment;
end;
$$;

revoke all on function public.submit_homework(bigint) from public;
grant execute on function public.submit_homework(bigint) to authenticated;

