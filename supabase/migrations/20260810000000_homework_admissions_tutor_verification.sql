create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  matched_tutor_registry_id text;
  requested_role text;
  initial_status text;
begin
  select registry_id
  into matched_tutor_registry_id
  from public.tutors
  where zoom_host_email is not null
    and lower(zoom_host_email) = lower(coalesce(new.email, ''))
  limit 1;

  requested_role := case
    when new.raw_user_meta_data ->> 'account_role' in ('student', 'parent', 'tutor')
      then new.raw_user_meta_data ->> 'account_role'
    else 'student'
  end;

  initial_status := case
    when coalesce(new.email, '') = 'ssapgoadmin@seonbae.internal' then 'approved'
    else 'pending'
  end;

  insert into public.profiles (
    id,
    email,
    full_name,
    role,
    tutor_registry_id,
    account_status
  )
  values (
    new.id,
    coalesce(new.email, ''),
    nullif(new.raw_user_meta_data ->> 'full_name', ''),
    case
      when matched_tutor_registry_id is not null then 'tutor'
      else requested_role
    end,
    matched_tutor_registry_id,
    initial_status
  )
  on conflict (id) do update
  set
    email = excluded.email,
    full_name = coalesce(public.profiles.full_name, excluded.full_name),
    role = case
      when public.profiles.role = 'admin' then 'admin'
      when matched_tutor_registry_id is not null then 'tutor'
      else public.profiles.role
    end,
    tutor_registry_id = coalesce(
      matched_tutor_registry_id,
      public.profiles.tutor_registry_id
    ),
    updated_at = now();

  return new;
end;
$$;

